const SYSTEM = ['id', 'created', 'updated', 'collectionid', 'collectionname', 'expand', 'fields', 'password', 'tokenkey', 'email', 'emailvisibility', 'verified', '_row_key', '_row_no', '_synced_at', '_hash'];
function normalise(cols) {
  const used = new Set(SYSTEM);
  return cols.map((c) => {
    let n = String(c.source_name).normalize('NFKD').replace(/[^\x00-\x7f]/g, '').toLowerCase()
      .replace(/[^a-z0-9]+/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
    if (!n) n = 'col';
    if (/^[0-9]/.test(n)) n = 'c_' + n;
    n = n.slice(0, 60);
    let out = n, k = 2;
    while (used.has(out)) out = n + '_' + k++;
    used.add(out);
    return Object.assign({}, c, { name: out });
  });
}

