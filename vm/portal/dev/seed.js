/* ---------- column names (contract normalisation) ---------- */
// Same reserved names as vm/sync/lib/normalise.js.
const SYSTEM = ['id', 'created', 'updated', 'collectionid', 'collectionname', 'expand', 'fields', 'password', 'tokenkey', 'email', 'emailvisibility', 'verified', '_row_key', '_row_no', '_synced_at', '_hash'];
function normalise(cols) {
  const used = new Set(SYSTEM);
  return cols.map((c) => {
    let n = String(c.source_name).normalize('NFKD').replace(/[^\x00-\x7f]/g, '').toLowerCase()
      .replace(/[^a-z0-9]+/g, '_').replace(/_+/g, '_').replace(/^_+|_+$/g, '');
    if (!n) n = 'col';
    if (/^[0-9]/.test(n)) n = 'c_' + n;
    n = n.slice(0, 60);
    let out = n, k = 2;
    while (used.has(out)) out = n + '_' + k++;
    used.add(out);
    return Object.assign({}, c, { name: out });
  });
}

const sha1 = (s) => crypto.createHash('sha1').update(s).digest('hex');
function sourceUrl(ds) {
  const r = ds.source_ref;
  if (ds.source_type === 'google_sheet') return 'https://docs.google.com/spreadsheets/d/' + r.spreadsheetId + '/edit#gid=' + r.gid;
  if (ds.source_type === 'supabase_table') return 'https://supabase.com/dashboard/project/' + r.project + '/editor';
  if (ds.source_type === 'supabase_storage') return 'https://supabase.com/dashboard/project/' + r.project + '/storage/buckets/' + r.bucket;
  if (ds.source_type === 'json_file') return 'https://github.com/smartlinemanapp/mzo-reports/blob/develop/' + r.file;
  return '';
}
const STATUS_OF = (s) => (s.error ? 'error' : s.skipped ? 'skipped' : s.unchanged ? 'unchanged' : 'ok');

