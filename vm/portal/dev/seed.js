/* ---------- credentials (random, local, git-ignored) ---------- */
function credentials() {
  if (fs.existsSync(CRED_FILE)) return JSON.parse(fs.readFileSync(CRED_FILE, 'utf8'));
  const pw = () => crypto.randomBytes(12).toString('base64url');
  const c = {
    note: 'Local dev PocketBase only. Generated by vm/portal/dev/seed.js.',
    superuser: { email: 'admin@portal.local', password: pw() },
    portal: { email: 'viewer@portal.local', password: pw() }
  };
  fs.mkdirSync(DEV_DIR, { recursive: true });
  fs.writeFileSync(CRED_FILE, JSON.stringify(c, null, 2) + '\n', { mode: 0o600 });
  return c;
}

/* ---------- tiny PocketBase client ---------- */
let TOKEN = '';
async function pb(method, url, body) {
  const res = await fetch(PB_URL + url, {
    method,
    headers: Object.assign({ 'content-type': 'application/json' }, TOKEN ? { Authorization: TOKEN } : {}),
    body: body === undefined ? undefined : JSON.stringify(body)
  });
  const text = await res.text();
  let data = null;
  try { data = text ? JSON.parse(text) : null; } catch (e) { data = text; }
  if (!res.ok) {
    const err = new Error(method + ' ' + url + ' → ' + res.status + ' ' + JSON.stringify(data).slice(0, 600));
    err.status = res.status;
    throw err;
  }
  return data;
}
async function dropCollection(name) {
  try { await pb('DELETE', '/api/collections/' + encodeURIComponent(name)); } catch (e) { if (e.status !== 404) throw e; }
}
async function batchInsert(collection, records) {
  for (let i = 0; i < records.length; i += BATCH) {
    const chunk = records.slice(i, i + BATCH);
    await pb('POST', '/api/batch', {
      requests: chunk.map((body) => ({ method: 'POST', url: '/api/collections/' + collection + '/records', body }))
    });
  }
}

