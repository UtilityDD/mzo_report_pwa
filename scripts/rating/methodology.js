#!/usr/bin/env node
/* scripts/rating/methodology.js: writes docs/rating/methodology.md from the engine itself, so the
 * document, the page's Methodology tab and the scores can never disagree.
 *
 *   node scripts/rating/methodology.js            write docs/rating/methodology.md
 *   node scripts/rating/methodology.js --check    exit 1 if the file is out of date
 *
 * Method and text: lib/rating.js (METHOD, ratingDoc.method). Data: docs/rating/sample-metrics.json.
 * Also reproduces the old performance_index.html formula on the same data for the comparison.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');
const R = require(path.join(REPO, 'lib', 'rating.js'));
const OUT = path.join(REPO, 'docs', 'rating', 'methodology.md');
const SAMPLE_PATH = path.join(REPO, 'docs', 'rating', 'sample-metrics.json');

// Worked examples: one office per level, chosen to show the rules at work.
const EXAMPLES = [
    { code: '6613103', why: 'a CCC where a whole pillar and several parameters are n/a, so both re-weighting rules show' },
    { code: '6622000', why: 'a division, with the CCCs\' share of its weak parameters' },
    { code: '6620000', why: 'a region whose loss figures include HT input booked at the region office' }
];

const f1 = (v) => (v == null ? '—' : Number(v).toFixed(1));
const f2 = (v) => (v == null ? '—' : Number(v).toFixed(2));
const esc = (s) => String(s == null ? '' : s).replace(/\|/g, '\\|');
const LEVEL = { zone: 'zone', region: 'regions', division: 'divisions', ccc: 'CCCs' };

/** The old index (performance_index.html before this rating): six parameters, each scaled 0-100
 * between the best and worst office of the level, weights 30/8/8/9/25/20, lower is better. */
function oldIndex(M, level) {
    const W = { atc: 30, qtn: 8, wo: 8, conn: 9, nsc: 25, mc: 20 };
    const offs = Object.keys(M.offices).sort().filter((c) => M.offices[c].level === level).map((c) => {
        const m = M.offices[c].metrics;
        return { code: c, name: M.offices[c].name, m: {
            atc: m.atc_loss.value, qtn: m.nsc_qtn_delay_avg.value || 0, wo: m.nsc_wo_delay_avg.value || 0, conn: m.nsc_pending_avg_days.value || 0,
            nsc: m.nsc_pending_over_30d_share.denominator || 0, mc: (m.mc_pending_over_30d_share.inputs || {}).days90OrMore || 0 } };
    });
    const st = {};
    for (const k in W) { const v = offs.map((x) => x.m[k]); st[k] = [Math.min(...v), Math.max(...v)]; }
    for (const x of offs) {
        let t = 0;
        for (const k in W) { const [lo, hi] = st[k]; const s = hi === lo ? 100 : 100 * (hi - x.m[k]) / (hi - lo); t += Math.max(0, Math.min(100, s)) * W[k] / 100; }
        x.old = t;
    }
    offs.sort((a, b) => b.old - a.old || (a.name < b.name ? -1 : 1));
    offs.forEach((x, i) => { x.oldRank = i + 1; });
    return offs;
}
function spearman(rows) {
    const n = rows.length;
    const d = rows.reduce((s, x) => s + (x.oldRank - x.newRank) ** 2, 0);
    return 1 - 6 * d / (n * (n * n - 1));
}

function paramTable(off) {
    const L = ['| Pillar | Parameter | Value | Full → zero marks at | Fraction | Marks | Note |', '|---|---|---|---|---:|---:|---|'];
    for (const p of off.pillars) {
        for (const x of p.params) {
            const note = x.status === 'na' ? 'n/a: ' + x.naReason : (x.notes || []).map((n) => n.text).join(' ');
            L.push('| ' + esc(p.short) + ' | ' + esc(x.label) + ' | ' + esc(x.display) + (x.detail ? ' (' + esc(x.detail) + ')' : '') + ' | ' + esc(R.fmtT(x.full, x.unit)) + ' → ' + esc(R.fmtT(x.zero, x.unit)) + ' | ' +
                (x.fraction == null ? '—' : x.fraction.toFixed(3)) + ' | ' + (x.status === 'na' ? '—' : f2(x.marks) + ' of ' + f2(x.effMax)) + ' | ' + esc(note) + ' |');
        }
        L.push('| **' + esc(p.label) + '** | | | | | **' + f2(p.marks) + ' of ' + f2(p.max) + '** | ' + esc(p.note || '') + ' |');
    }
    return L;
}

function render(d, M) {
    const m = d.method, offs = d.offices, z = offs[d.zone];
    const L = [];
    const P = (s) => { L.push(s); L.push(''); };
    P('# ' + m.title + ': methodology');
    P('> Generated by `node scripts/rating/methodology.js` from the engine (`lib/rating.js`) and the office metrics of ' + d.referenceDate + ' (`docs/rating/sample-metrics.json`). Edit those, not this file: `node --test scripts/qa/rating.test.js` fails when this file is out of date. The page\'s Methodology tab shows the same content from the engine output (`ratingDoc.method`). Research and data behind it: [sources.md](sources.md), [data-map.md](data-map.md); interface: [engine-contract.md](engine-contract.md).');

    P('## What this is');
    for (const p of m.intro) P(p);
    P('**Scoring:** ' + m.formula + '. The pillar marks add up to 100; penalties are taken off; the score is kept between 0 and 100.');

    P('## Grade bands');
    L.push('| Grade | Score | Reading |', '|---|---|---|');
    m.bands.forEach((b, i) => L.push('| ' + b.grade + ' | ' + (i === 0 ? b.min + ' and above' : b.min == null ? 'under ' + m.bands[i - 1].min : b.min + ' to under ' + m.bands[i - 1].min) + ' | ' + b.label + ' |'));
    L.push('');
    P(m.bandsNote + ' Source: REC CSRD FY 2023-24 p.73 and FY 2024-25 PDF p.37.');

    P('## Pillars and weights');
    L.push('| Pillar | Weight | National reference | Why this weight |', '|---|---:|---|---|');
    for (const p of m.pillars) L.push('| ' + esc(p.label) + ' | ' + p.weight + ' | ' + esc(p.national) + ' | ' + esc(p.basis) + ' |');
    L.push('| **Total** | **100** | | |', '');
    P('Inside each pillar the parameter marks add up to the pillar weight. The national ratings weigh reliability most (CSRD 45). Here it gets 15, because the data behind it is the thinnest: no consumers per feeder, no DT failure register, and CCCs only through a name match. Connection services get more (20 against 10) because those lists are complete and current at every level.');

    P('## Parameters');
    P('"Full" is the value that earns all the marks, "zero" the value that earns none; in between, marks are in proportion. Levels: where the parameter can be measured (elsewhere it is n/a, see below).');
    for (const p of m.pillars) {
        P('### ' + p.label + ' (' + p.weight + ')');
        L.push('| Parameter | Formula | Full | Zero | Marks | Source | Levels |', '|---|---|---|---|---:|---|---|');
        for (const x of p.params) L.push('| ' + esc(x.label) + ' | ' + esc(x.formula) + ' | ' + esc(x.fullDisplay) + ' | ' + esc(x.zeroDisplay) + ' | ' + x.max + ' | ' + esc(x.source.short) + ' | ' + (x.levels ? x.levels.join(', ') : '—') + ' |');
        L.push('');
        for (const x of p.params) {
            L.push('- **' + x.label + '.** ' + x.ref + '.' + (x.stretch ? ' Stretch reference, not scored: ' + x.stretch + '.' : '') + (x.notes.length ? ' ' + x.notes.join(' ') + '.' : '') +
                ' Data: ' + x.datasets.map((k) => k.label + ' (`' + k.key + '`' + (k.page ? ', ' + k.page : '') + ')').join(', ') + '.');
        }
        L.push('');
    }

    P('## Safety penalties');
    for (const p of m.penaltyRule) P(p);
    L.push('| Penalty | Formula | No deduction at | Full deduction at | Marks | Source |', '|---|---|---|---|---:|---|');
    for (const p of m.penalties) L.push('| ' + esc(p.label) + ' | ' + esc(p.formula) + ' | ' + esc(p.noneDisplay) + ' | ' + esc(p.worstDisplay) + ' | −' + p.max + ' | ' + esc(p.ref) + ' |');
    L.push('| **Cap** | | | | **−' + m.penaltyCap + '** | |', '');

    P('## Levels: regions, divisions and CCCs');
    for (const p of m.levelsRule) P(p);
    P('## When a parameter cannot be measured');
    for (const p of m.naRule) P(p);
    P('## Data quality');
    L.push(m.qualityRule[0], '');
    for (const p of m.qualityRule.slice(1)) L.push('- ' + p);
    L.push('');
    P('## Ranks, "why this grade" and "what would move it up"');
    P(m.rankRule);
    P(m.whyRule);

    P('## This run\'s data caveats');
    for (const c of m.caveats) L.push('- ' + c.text);
    L.push('');

    P('## Results on ' + d.referenceDate);
    P('**Malda Zone: ' + f1(z.score) + ', grade ' + z.grade + '.** ' + z.why.slice(1).join(' '));
    for (const lv of ['region', 'division']) {
        L.push('| Rank | ' + (lv === 'region' ? 'Region' : 'Division') + ' | Score | Grade | ' + m.pillars.map((p) => esc(p.short) + ' (' + p.weight + ')').join(' | ') + ' |', '|---:|---|---:|---|' + m.pillars.map(() => '---:').join('|') + '|');
        for (const c of d.levels[lv].order) {
            const o = offs[c];
            L.push('| ' + (o.rank || '—') + ' of ' + o.of + ' | ' + esc(o.name) + ' | ' + f1(o.score) + ' | ' + (o.grade || '—') + ' | ' + o.pillars.map((p) => f1(p.marks)).join(' | ') + ' |');
        }
        L.push('');
    }
    const cc = d.levels.ccc.order.map((c) => offs[c]);
    const counts = {};
    for (const o of cc) if (o.grade) counts[o.grade] = (counts[o.grade] || 0) + 1;
    P('CCCs: ' + m.bands.filter((b) => counts[b.grade]).map((b) => counts[b.grade] + ' ' + b.grade).join(', ') + '. Top five: ' + cc.slice(0, 5).map((o) => o.name + ' ' + f1(o.score) + ' (' + o.grade + ')').join(', ') +
        '. Bottom five: ' + cc.slice(-5).map((o) => o.name + ' ' + f1(o.score) + ' (' + o.grade + ')').join(', ') + '. Every office\'s full scorecard is in [sample-rating.json](sample-rating.json).');

    P('## Worked examples');
    P('All numbers are from the run of ' + d.referenceDate + '. "Marks" shows marks earned of the parameter\'s maximum after re-weighting; fraction = (value − zero) ÷ (full − zero), kept between 0 and 1.');
    for (const ex of EXAMPLES) {
        const o = offs[ex.code];
        if (!o) continue;
        P('### ' + { ccc: 'CCC', division: 'Division', region: 'Region' }[o.level] + ': ' + o.name + ' (' + o.code + ')');
        P('Chosen as ' + ex.why + '. Score **' + f2(o.score) + '**, grade **' + o.grade + '**, rank ' + o.rank + ' of ' + o.of + ' ' + LEVEL[o.level] + '.');
        for (const s of paramTable(o)) L.push(s);
        L.push('');
        const naP = o.pillars.filter((p) => p.na);
        const parts = [];
        if (naP.length) {
            const rest = 100 - naP.reduce((s, p) => s + p.weight, 0);
            parts.push(naP.map((p) => p.label).join(' and ') + ' cannot be measured here, so ' + (naP.length > 1 ? 'their ' : 'its ') + naP.reduce((s, p) => s + p.weight, 0) + ' marks go to the other pillars: each pillar\'s weight is multiplied by 100 ÷ ' + rest + ' (' + o.pillars.filter((p) => !p.na).map((p) => p.weight + ' → ' + f2(p.max)).join(', ') + ').');
        }
        for (const p of o.pillars) {
            if (p.na) continue;
            const na = p.params.filter((x) => x.status === 'na');
            if (!na.length) continue;
            const live = p.params.filter((x) => x.status !== 'na');
            parts.push('In ' + p.label + ', ' + na.map((x) => x.label).join(' and ') + (na.length > 1 ? ' are' : ' is') + ' n/a, so the pillar\'s ' + f2(p.max) + ' marks are shared by ' + live.map((x) => x.label + ' (base ' + x.max + ' → ' + f2(x.effMax) + ')').join(', ') + ', in proportion to their base marks.');
        }
        const own = o.level === 'region' && M.offices[o.code].metrics.atc_loss.ownLevel;
        if (own) {
            const a = M.offices[o.code].metrics.atc_loss;
            const divOnly = 100 * (a.numerator - own.numerator) / (a.denominator - own.denominator);
            parts.push('Of the region\'s ' + f2(a.denominator) + ' MU input, ' + f2(own.denominator) + ' MU is HT input booked at the region office itself, with a loss of ' + f2(own.numerator) + ' MU (' + f2(100 * own.numerator / own.denominator) + ' %). Its divisions alone would give an AT&C loss of ' + f2(divOnly) + ' %; with the HT input the region\'s own figure is ' + f2(a.value) + ' %, and that is what is scored. The "booked at the region itself" row below is that HT input.');
        }
        parts.push('Pillars ' + o.pillars.filter((p) => !p.na).map((p) => f2(p.marks)).join(' + ') + ' = ' + f2(o.base) + (o.penaltyTotal ? ', penalties ' + f2(o.penaltyTotal) : ', no penalties (the safety registers are stale)') + ': score ' + f2(o.score) + ', in the ' + o.grade + ' band (' + o.band.min + (o.grade === 'A+' ? ' and above' : ' to under ' + o.band.max) + ').');
        P(parts.join(' '));
        if (o.improve.length) { L.push('What would move it up:', ''); for (const it of o.improve) L.push('- ' + it.text); L.push(''); }
        const ids = Object.keys(o.contributions);
        if (ids.length) {
            const pick = ids.slice(0, 3);
            P('How the ' + (o.level === 'region' ? 'divisions' : 'CCCs') + ' contribute to its weakest parameters (excess over the full-marks level; rows add up to the ' + o.level + '\'s excess):');
            for (const id of pick) {
                const c = o.contributions[id];
                L.push('**' + c.label + '** (' + o.name + ' ' + f2(c.parentExcess) + ' ' + c.unit + ' over): ' + c.rows.map((r) => r.name + ' ' + f2(r.excess) + (r.share ? ' (' + Math.round(100 * r.share) + ' %)' : '')).join(', ') + '.', '');
            }
        }
    }

    P('## How this compares with the old performance index');
    P('The old index scored six parameters (AT&C loss 30, pending NSC count 25, master cards over 3 months 20, connection delay 9, quotation and work-order delay 8 each) and scaled each one between the best and the worst office of the level, so the best office always got full marks and the worst none, whatever their actual performance. Recomputed on the same data:');
    for (const lv of ['region', 'division', 'ccc']) {
        const rows = oldIndex(M, lv).map((x) => Object.assign(x, { newRank: offs[x.code].rank, score: offs[x.code].score, grade: offs[x.code].grade }));
        const rho = spearman(rows);
        if (lv !== 'ccc') {
            L.push('| ' + (lv === 'region' ? 'Region' : 'Division') + ' | New rank | Score, grade | Old rank | Old index |', '|---|---:|---|---:|---:|');
            for (const x of rows.slice().sort((a, b) => a.newRank - b.newRank)) L.push('| ' + esc(x.name) + ' | ' + x.newRank + ' | ' + f1(x.score) + ', ' + x.grade + ' | ' + x.oldRank + ' | ' + f1(x.old) + ' |');
            L.push('', 'Rank correlation with the old index (Spearman): ' + rho.toFixed(2) + '.', '');
        } else {
            const up = rows.slice().sort((a, b) => (b.oldRank - b.newRank) - (a.oldRank - a.newRank) || (a.name < b.name ? -1 : 1));
            P('CCCs: rank correlation ' + rho.toFixed(2) + '. Moved up most: ' + up.slice(0, 5).map((x) => x.name + ' ' + x.oldRank + ' → ' + x.newRank).join(', ') + '. Moved down most: ' + up.slice(-5).reverse().map((x) => x.name + ' ' + x.oldRank + ' → ' + x.newRank).join(', ') + '.');
        }
    }
    P('Why they differ:');
    L.push('- **Absolute standards, not best-versus-worst.** A parameter now earns marks against a fixed benchmark (RDSS, WBERC, CSRD, PFC), so an office can improve its marks without another office getting worse, and a level where every office is weak (load extensions pending beyond 90 days) gives everyone few marks instead of full marks to the least bad.');
    L.push('- **Shares and rates instead of raw counts.** The old index gave 45 of 100 to the size of the pending NSC and master-card lists, so big offices lost marks for being big (Kaliyaganj, Gazole and Raiganj CCCs, with 146-374 pending applications) and small ones gained (Patiram, Buniadpur, Manikchak). The new rating uses the share pending beyond the WBERC timeline and rates per 10,000 consumers.');
    L.push('- **Five pillars instead of two.** Reliability, metering and billing, receivables, collection, and faults and grievances were not in the old index. Balurghat and Buniadpur divisions led it on short pending lists; with 1,121 and 1,143 open dockets and the lowest supply availability (97.6 %) they now rank 4th and 6th. Sujapur, Kaliachak and Samsi rose on few connections overdue beyond 30 days, full or nearly full reliability marks and few open fault dockets; Patiram and Kusmandi fell on supply availability and open fault dockets, Manikchak on overdue connections, receivables and defective meters.');
    L.push('- **Missing data is not perfect data.** The old index counted an office with no loss row as 0 % AT&C loss (full marks) and an empty list as the best value. Here a missing, stale, too-small or unmatched input is n/a and its weight is shared, so it neither costs nor earns marks.');
    L.push('');

    P('## Left out, and why');
    L.push('| Item | Reason |', '|---|---|');
    for (const x of m.excluded) L.push('| ' + esc(x.item) + ' | ' + esc(x.reason) + ' |');
    L.push('');
    P('## Data that would make it better');
    for (const g of m.gaps) L.push('- ' + g);
    L.push('');
    P('## Sources');
    for (const s of m.sources) L.push('- **' + s.short + '**: ' + s.label + (s.url ? ', <' + s.url + '>' : '') + '. ' + s.ref + '.');
    L.push('');
    P('## Reproduce');
    L.push('```bash',
        'node --test scripts/qa/rating.test.js                       # engine tests, incl. the WBSEDCL 14th Integrated Rating calibration',
        'node scripts/rating/methodology.js                          # this file',
        'node -e "const R=require(\'./lib/rating.js\');process.stdout.write(JSON.stringify(R.rate(require(\'./docs/rating/sample-metrics.json\')),null,1)+\'\\n\')" > docs/rating/sample-rating.json',
        '```', '');
    return L.join('\n').replace(/\n{3,}/g, '\n\n');
}

function build() {
    const M = JSON.parse(fs.readFileSync(SAMPLE_PATH, 'utf8'));
    const d = R.rate(M);
    return render(d, M);
}

if (require.main === module) {
    const text = build();
    if (process.argv.includes('--check')) {
        const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
        if (cur !== text) { process.stderr.write('docs/rating/methodology.md is out of date: run node scripts/rating/methodology.js\n'); process.exit(1); }
        process.stdout.write('methodology.md is current\n');
    } else {
        fs.writeFileSync(OUT, text);
        process.stdout.write('wrote ' + path.relative(REPO, OUT) + ' (' + text.length + ' bytes)\n');
    }
}
module.exports = { build, render, oldIndex, OUT };
